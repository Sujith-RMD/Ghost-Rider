import { useState } from "react";
import { useQuery } from "@tanstack/react-query";
import { Link, useNavigate, useParams, useSearchParams } from "react-router-dom";
import { createReport, readReport, type ActualReport } from "../../api/real-assessment";
import { recentSampleIds } from "../../api/recent-samples";
import { Card } from "../../components/primitives";

export default function ActualReportsPage() {
  const { id } = useParams();
  const [params] = useSearchParams();
  const suggested = params.get("sample") || "";
  const ids = [...new Set([suggested, ...recentSampleIds()].filter(Boolean))];
  const [selected, setSelected] = useState(suggested || ids[0] || "");
  const [narrative, setNarrative] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const navigate = useNavigate();
  const query = useQuery({ queryKey: ["saved-report", id], queryFn: () => readReport(id!), enabled: !!id, retry: false });

  async function generate() {
    if (!selected || busy) return;
    setBusy(true); setError(null);
    try {
      const report = await createReport(selected, narrative);
      navigate(`/reports/${encodeURIComponent(report.report_id)}`);
    } catch (cause) {
      setError(cause instanceof Error ? cause.message : "Could not generate the report.");
    } finally { setBusy(false); }
  }
  return <div className="content-page report-page">
    <div className="page-heading"><div><h1>{id ? "Inspection report" : "Inspection reports"}</h1><p>Stored evidence, declared limitations and inspection recommendations.</p></div></div>
    {id ? <>
      <Link className="back-link" to="/reports">Back to reports</Link>
      {query.isPending ? <p>Loading saved report…</p> : query.isError ? <p role="alert">{query.error.message}</p> : query.data && <SavedReport report={query.data} />}
    </> : <Card title="Generate a report">
      {ids.length ? <>
        <label htmlFor="report-sample">Assessment</label>
        <select id="report-sample" className="report-assessment-select" value={selected} onChange={(event) => setSelected(event.target.value)} disabled={busy}>
          {ids.map((sampleId) => <option key={sampleId} value={sampleId}>Sample {sampleId}</option>)}
        </select>
        <p><label><input type="checkbox" checked={narrative} onChange={(event) => setNarrative(event.target.checked)} disabled={busy} /> Request a Bedrock explanation</label></p>
        <p>Findings come from the saved assessment. If Bedrock is unavailable, the report uses a clearly labelled factual template.</p>
        <button className="button primary" disabled={busy || !selected} onClick={() => void generate()}>{busy ? "Generating report…" : "Generate report"}</button>
        {error && <p role="alert">{error}</p>}
      </> : <p>No completed assessments saved in this browser. <Link to="/assess">Assess an image</Link> or open a saved sample to generate its report.</p>}
    </Card>}
  </div>;
}

function SavedReport({ report }: { report: ActualReport }) {
  const content = report.content;
  const references = content.evidence_references ?? [];
  const limitations = content.limitations ?? [];
  const actions = content.inspection_actions ?? [];
  function download() {
    const url = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: "application/json" }));
    const link = document.createElement("a");
    link.href = url; link.download = `roadsight-report-${report.report_id}.json`; link.click();
    URL.revokeObjectURL(url);
  }
  return <>
    <Card title="Findings">
      <span className="chip">{content.narrative_status === "generated" ? "Generated by Bedrock" : content.narrative_status === "fallback" ? "Template fallback" : "Factual summary"}</span>
      {content.narrative_status === "fallback" && <p>Bedrock was unavailable or its response could not be accepted. This summary uses the stored facts.</p>}
      <p>{content.summary}</p>
      {report.bedrock_model_id && <p>Model: {report.bedrock_model_id}</p>}
      <p>Generated: {report.generated_at}</p>
      <button className="button secondary" onClick={download}>Download report JSON</button>
    </Card>
    <Card title="Evidence"><ul className="plain-list">{references.map((reference) => <li key={reference}>{reference.startsWith("sample:") ? <Link to={`/samples/${encodeURIComponent(reference.slice(7))}`}>{reference}</Link> : reference}</li>)}</ul></Card>
    <Card title="Limitations">{limitations.length ? <ul className="plain-list">{limitations.map((item) => <li key={item}>{item}</li>)}</ul> : <p>No limitations were supplied with this report.</p>}</Card>
    <Card title="Recommended inspection actions">{actions.length ? <ul className="plain-list">{actions.map((item) => <li key={item}>{item}</li>)}</ul> : <p>No inspection actions supplied.</p>}</Card>
  </>;
}
