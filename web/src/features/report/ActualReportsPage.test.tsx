import { expect, test, vi } from "vitest";
import { fireEvent, render, screen } from "@testing-library/react";
import { MemoryRouter, Route, Routes } from "react-router-dom";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { createReport } from "../../api/real-assessment";
import ActualReportsPage from "./ActualReportsPage";

vi.mock("../../api/real-assessment", () => ({
  createReport: vi.fn(async () => ({ report_id: "report-1" })),
  readReport: vi.fn(async () => ({ report_id: "report-1", generated_at: "2026-10-16T06:00:00Z", content: {
    summary: "Numerical SQI withheld.", narrative_status: "fallback", evidence_references: ["sample:sample-1"],
    limitations: ["Uncalibrated scale"], inspection_actions: ["Review the source image"],
  } })),
}));

test("a selected stored assessment generates and reopens an honest fallback report", async () => {
  render(<QueryClientProvider client={new QueryClient()}><MemoryRouter initialEntries={["/reports?sample=sample-1"]}><Routes>
    <Route path="/reports" element={<ActualReportsPage />} />
    <Route path="/reports/:id" element={<ActualReportsPage />} />
  </Routes></MemoryRouter></QueryClientProvider>);
  fireEvent.click(screen.getByRole("button", { name: "Generate report" }));
  expect(await screen.findByText("Template fallback")).toBeVisible();
  expect(createReport).toHaveBeenCalledWith("sample-1", false);
  expect(screen.getByText("Uncalibrated scale")).toBeVisible();
  expect(screen.getByRole("link", { name: "sample:sample-1" })).toHaveAttribute("href", "/samples/sample-1");
  expect(screen.queryByText("Generated by Bedrock")).not.toBeInTheDocument();
});
