import { formatTimestamp } from "../../lib/format";
import { Link, useParams } from "react-router-dom";
import type { Report } from "../../api/display";
import {
  Card,
  EmptyState,
  MetricValue,
  SourceModeChip,
} from "../../components/primitives";
export function ReportView({ report }: { report: Report }) {
  return (
    <>
      <Card title="Structured findings">
        <dl>
          {report.facts.map((f) => (
            <div key={f.label}>
              <dt>{f.label}</dt>
              <dd>
                <MetricValue metric={f.metric} />
              </dd>
            </div>
          ))}
        </dl>
      </Card>
      <Card title="Supporting explanation">
        <span className="chip">
          {report.fallback ? "Template summary" : "Generated by Bedrock"}
        </span>
        {!report.fallback && (
          <p>Model: {report.modelId ?? "Model ID not supplied"}</p>
        )}
        {report.fallback && (
          <p className="muted">
            The language model was unavailable, so this summary was built from a
            template.
          </p>
        )}
        <p className="narrative">{report.narrative}</p>
        <div className="chip-row">
          {report.references.map((r) =>
            r.href ? (
              <Link className="chip reference-chip" to={r.href} key={r.id}>
                {r.label}
              </Link>
            ) : (
              <span className="chip review" key={r.id}>
                Unverified reference: {r.label}
              </span>
            ),
          )}
        </div>
      </Card>
      <Card title="Limitations">
        {report.limitations.length ? (
          <ul className="plain-list">
            {report.limitations.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        ) : (
          <p role="alert" className="review-copy">
            The report did not include limitations.
          </p>
        )}
      </Card>
      <Card title="Recommended inspection actions">
        {report.actions.length ? (
          <ul className="plain-list">
            {report.actions.map((s) => (
              <li key={s}>{s}</li>
            ))}
          </ul>
        ) : (
          <p role="alert" className="review-copy">
            The report did not include inspection actions.
          </p>
        )}
      </Card>
    </>
  );
}
export default function ReportPage({ report }: { report: Report }) {
  const { id } = useParams();
  if (id !== report.id)
    return (
      <EmptyState title="Report not found">
        Choose an available report.
      </EmptyState>
    );
  return (
    <div className="content-page report-page">
      <div className="page-heading">
        <div>
          <h1>Inspection report</h1>
          <p>
            {report.version} / {formatTimestamp(report.createdAt)}
          </p>
        </div>
        <div className="chip-row">
          <SourceModeChip mode={report.mode} />
          {report.exportUrl ? (
            <a
              className="button primary"
              href={report.exportUrl}
              target="_blank"
              rel="noreferrer"
            >
              Export report
            </a>
          ) : (
            <button
              className="button secondary"
              disabled
              title="No backend report export URL supplied"
            >
              Export report
            </button>
          )}
        </div>
      </div>
      <ReportView report={report} />
    </div>
  );
}
